#!/usr/bin/env python3
"""Render and check a hierarchical index over Markdown ticket files.

Facts come from ticket frontmatter (``.tickets/*.md`` by default). Module
ownership and one-line summaries come from ``ticket-index.toml``. The generated
Markdown is a deterministic projection, so ``check`` can detect both drift and
hand edits, and ``diff`` can show exactly what a render would change.

Commands:
    facts   compact tab-separated fact sheet for review
    check   validate config and generated files (exit 1 on problems)
    diff    show what render would change, without writing
    render  write INDEX.md and modules/*.md
    new-id  print one unused ticket id for parallel ticket creation

Only the Python standard library is required (Python 3.11+ for ``tomllib``).
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import os
import random
import re
import sys
import tempfile
import threading
from collections import Counter, defaultdict
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover
    print("Python 3.11+ is required (tomllib).", file=sys.stderr)
    raise SystemExit(2)

DEFAULT_ID_PATTERN = r"[A-Za-z][A-Za-z0-9]*-[0-9a-z]{4}"
GENERATED_MARK = "<!-- generated by ticket-index; do not edit -->"
ACTIVE_STATUSES = {"open", "in_progress"}
STATUS_ORDER = {"in_progress": 0, "open": 1, "closed": 2}
DEFAULT_PLACEHOLDERS = frozenset({"", "-", "team", "tbd", "todo", "unassigned"})
MODULE_ID_RE = re.compile(r"[a-z0-9][a-z0-9-]*")
_RENDER_LOCKS: dict[str, threading.RLock] = {}
_RENDER_LOCKS_GUARD = threading.Lock()


@contextmanager
def render_lock(root: Path) -> Iterator[None]:
    """Serialize renders targeting the same repository across threads and processes."""
    lock_root = Path(tempfile.gettempdir()) / "ticket-index-render-locks"
    normalized_root = str(root.resolve())
    if os.name == "nt":
        normalized_root = normalized_root.casefold()
    lock_name = hashlib.sha256(normalized_root.encode("utf-8")).hexdigest() + ".lock"
    lock_path = lock_root / lock_name
    key = str(lock_path)
    with _RENDER_LOCKS_GUARD:
        lock = _RENDER_LOCKS.setdefault(key, threading.RLock())
    with lock:
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        with lock_path.open("a+b") as stream:
            if os.name == "nt":
                import msvcrt

                stream.seek(0, os.SEEK_END)
                if stream.tell() == 0:
                    stream.write(b"0")
                    stream.flush()
                stream.seek(0)
                msvcrt.locking(stream.fileno(), msvcrt.LK_LOCK, 1)
                try:
                    yield
                finally:
                    stream.seek(0)
                    msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                import fcntl

                fcntl.flock(stream.fileno(), fcntl.LOCK_EX)
                try:
                    yield
                finally:
                    fcntl.flock(stream.fileno(), fcntl.LOCK_UN)


# ---------------------------------------------------------------------------
# Configuration


@dataclass(frozen=True)
class Settings:
    title: str
    tickets_dir: Path
    output_dir: Path
    config_path: Path
    id_pattern: str
    summary_max_chars: int
    placeholders: frozenset[str]


@dataclass(frozen=True)
class Module:
    id: str
    title: str
    scope: str


@dataclass(frozen=True)
class Config:
    root: Path
    settings: Settings
    modules: list[Module]
    entries: dict[str, dict]


def locate_root(config_path: Path) -> Path:
    """Return the repository root for a config file.

    ``<root>/ticket-index.toml`` is the primary layout. The legacy layout
    ``<root>/docs/tickets/index.toml`` is also recognised.
    """
    parent = config_path.parent
    if config_path.name == "index.toml" and parent.name == "tickets" and parent.parent.name == "docs":
        return parent.parent.parent
    return parent


def find_config(explicit: str | None) -> Path:
    if explicit:
        path = Path(explicit)
        if not path.is_file():
            raise SystemExit(f"Config not found: {explicit}")
        return path.resolve()
    for base in (Path.cwd().resolve(), *Path.cwd().resolve().parents):
        for relative in ("ticket-index.toml", "docs/tickets/index.toml"):
            candidate = base / relative
            if candidate.is_file():
                return candidate.resolve()
    raise SystemExit(
        "No ticket-index.toml found. Create one at the repository root or pass --config."
    )


def load_config(config_path: Path) -> Config:
    root = locate_root(config_path)
    try:
        raw = tomllib.loads(config_path.read_text(encoding="utf-8-sig"))
    except tomllib.TOMLDecodeError as exc:
        raise SystemExit(f"{config_path} is not valid TOML: {exc}")

    raw_settings = raw.get("settings", {})
    if not isinstance(raw_settings, dict):
        raise SystemExit("The [settings] table must be a table.")

    default_output = (
        config_path.parent
        if config_path.name == "index.toml" and config_path.parent.name == "tickets"
        else root / "docs/tickets"
    )

    def path_setting(key: str, default: Path) -> Path:
        value = raw_settings.get(key)
        if value is None:
            return default
        path = Path(str(value))
        return path if path.is_absolute() else (root / path)

    placeholders = raw_settings.get("placeholder_assignees", sorted(DEFAULT_PLACEHOLDERS))
    if not isinstance(placeholders, list) or not all(isinstance(item, str) for item in placeholders):
        raise SystemExit("[settings].placeholder_assignees must be an array of strings.")

    try:
        summary_max_chars = int(raw_settings.get("summary_max_chars", 160))
    except (TypeError, ValueError):
        raise SystemExit("[settings].summary_max_chars must be an integer.")

    settings = Settings(
        title=str(raw_settings.get("title", "Ticket Index")),
        tickets_dir=path_setting("tickets_dir", root / ".tickets"),
        output_dir=path_setting("output_dir", default_output),
        config_path=config_path,
        id_pattern=str(raw_settings.get("id_pattern", DEFAULT_ID_PATTERN)),
        summary_max_chars=summary_max_chars,
        placeholders=frozenset(item.strip().lower() for item in placeholders),
    )

    modules: list[Module] = []
    for item in raw.get("modules", []):
        if not isinstance(item, dict):
            raise SystemExit("Each [[modules]] entry must be a table.")
        modules.append(
            Module(
                id=str(item.get("id", "")).strip(),
                title=str(item.get("title", "")).strip(),
                scope=str(item.get("scope", "")).strip(),
            )
        )

    raw_entries = raw.get("tickets", {})
    if not isinstance(raw_entries, dict):
        raise SystemExit("The [tickets] table must be a table.")
    entries: dict[str, dict] = {}
    for ticket_id, value in raw_entries.items():
        if not isinstance(value, dict):
            raise SystemExit(f"[tickets].{ticket_id} must be an inline table.")
        entries[str(ticket_id)] = value

    return Config(root=root, settings=settings, modules=modules, entries=entries)


# ---------------------------------------------------------------------------
# Ticket parsing


@dataclass(frozen=True)
class Ticket:
    id: str
    title: str
    status: str
    type: str
    priority: int
    assignee: str
    parent: str | None
    deps: tuple[str, ...]
    links: tuple[str, ...]
    tags: tuple[str, ...]
    created: str

    @property
    def active(self) -> bool:
        return self.status in ACTIVE_STATUSES

    @property
    def is_map(self) -> bool:
        return "map" in self.tags or "wayfinder:map" in self.tags


def _strip_comment(value: str) -> str:
    quote = None
    for index, char in enumerate(value):
        if quote:
            if char == quote:
                quote = None
        elif char in "\"'":
            quote = char
        elif char == "#" and index > 0 and value[index - 1] in " \t":
            return value[:index]
    return value


def _scalar(raw: str) -> str:
    value = _strip_comment(raw).strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def _ids(raw: str, pattern: re.Pattern[str]) -> tuple[str, ...]:
    return tuple(match.group(0) for match in pattern.finditer(_strip_comment(raw)))


def parse_ticket(path: Path, id_pattern: re.Pattern[str]) -> Ticket:
    text = path.read_text(encoding="utf-8-sig")
    lines = text.splitlines()
    meta: dict[str, str] = {}
    body_start = 0
    if lines and lines[0].strip() == "---":
        for index in range(1, len(lines)):
            if lines[index].strip() == "---":
                body_start = index + 1
                break
        for line in lines[1:body_start]:
            if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
                continue
            key, _, value = line.partition(":")
            meta[key.strip()] = value

    title = ""
    for line in lines[body_start:]:
        if line.startswith("# "):
            title = line[2:].strip()
            break

    try:
        priority = int(_scalar(meta.get("priority", "2")))
    except ValueError:
        priority = 2

    return Ticket(
        id=_scalar(meta.get("id", "")).strip() or path.stem,
        title=title or path.stem,
        status=_scalar(meta.get("status", "open")) or "open",
        type=_scalar(meta.get("type", "task")) or "task",
        priority=priority,
        assignee=_scalar(meta.get("assignee", "")),
        parent=(_ids(meta.get("parent", ""), id_pattern) or (None,))[0],
        deps=_ids(meta.get("deps", ""), id_pattern),
        links=_ids(meta.get("links", ""), id_pattern),
        tags=tuple(
            tag.strip().strip("\"'")
            for tag in _strip_comment(meta.get("tags", "")).strip().strip("[]").split(",")
            if tag.strip()
        ),
        created=_scalar(meta.get("created", "")),
    )


def cell(text: str) -> str:
    """Keep Markdown table rows intact when text contains a pipe."""
    return text.replace("|", "\\|").replace("\n", " ")


def relative_link(target: Path, start: Path) -> str:
    return Path(os.path.relpath(target, start)).as_posix()


# ---------------------------------------------------------------------------
# Index model


class Index:
    def __init__(self, config: Config) -> None:
        self.root = config.root
        self.settings = config.settings
        self.modules = config.modules
        self.entries = config.entries
        self.tickets: dict[str, Ticket] = {}
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self._sorted_cache: list[Ticket] | None = None
        self._module_tickets_cache: dict[str, list[Ticket]] | None = None
        self._module_memberships_cache: dict[str, list[Ticket]] | None = None
        self._module_stats_cache: dict[str, dict[str, int]] = {}
        self._unresolved_cache: dict[str, list[str]] = {}
        self._modules_by_id = {module.id: module for module in self.modules}
        try:
            self.id_pattern = re.compile(self.settings.id_pattern)
        except re.error as exc:
            raise SystemExit(f"Invalid [settings].id_pattern: {exc}")
        self._load()

    # -- loading and validation -------------------------------------------

    def _load(self) -> None:
        tickets_dir = self.settings.tickets_dir
        if not tickets_dir.is_dir():
            self.errors.append(f"Tickets directory not found: {tickets_dir}")
        else:
            for path in sorted(tickets_dir.glob("*.md")):
                if path.stem.lower() == "readme":
                    continue
                if not self.id_pattern.fullmatch(path.stem):
                    self.warnings.append(f"Ignoring non-ticket file: {path.name}")
                    continue
                ticket = parse_ticket(path, self.id_pattern)
                if ticket.id != path.stem:
                    self.errors.append(
                        f"{path.name}: frontmatter id `{ticket.id}` does not match the filename"
                    )
                    continue
                self.tickets[ticket.id] = ticket

        module_ids = [module.id for module in self.modules]
        for module in self.modules:
            if not MODULE_ID_RE.fullmatch(module.id):
                self.errors.append(
                    f"Invalid module id `{module.id}` (lowercase letters, digits, and hyphens only)"
                )
            if not module.title:
                self.errors.append(f"Module `{module.id}` is missing a title")
        for duplicate, count in Counter(module_ids).items():
            if count > 1:
                self.errors.append(f"Duplicate module id `{duplicate}`")

        for ticket_id, raw in self.entries.items():
            if ticket_id not in self.tickets:
                self.errors.append(f"{self.config_name()}: `{ticket_id}` is not a ticket file")
                continue
            raw_modules = raw.get("module", [])
            if isinstance(raw_modules, str):
                modules = [raw_modules]
            elif isinstance(raw_modules, list) and all(isinstance(item, str) for item in raw_modules):
                modules = list(raw_modules)
            else:
                self.errors.append(
                    f"{self.config_name()}: `{ticket_id}` module must be a string or string array"
                )
                continue
            if not modules:
                self.errors.append(f"{self.config_name()}: `{ticket_id}` has no module")
                continue
            if len(set(modules)) != len(modules):
                self.errors.append(f"{self.config_name()}: `{ticket_id}` repeats a module")
            unknown = [module for module in modules if module not in module_ids]
            if unknown:
                self.errors.append(
                    f"{self.config_name()}: `{ticket_id}` uses unknown modules {', '.join(unknown)}"
                )
                continue
            summary = str(raw.get("summary", "")).strip()
            if not summary:
                self.errors.append(f"{self.config_name()}: `{ticket_id}` has no summary")
            elif len(summary) > self.settings.summary_max_chars:
                self.warnings.append(
                    f"{self.config_name()}: `{ticket_id}` summary is {len(summary)} characters "
                    f"(limit {self.settings.summary_max_chars})"
                )
            self.entries[ticket_id] = {"modules": tuple(modules), "summary": summary}

        for ticket_id in self.tickets:
            if ticket_id not in self.entries:
                self.errors.append(
                    f"{self.config_name()}: missing module and summary for `{ticket_id}`"
                )

        for ticket in self.tickets.values():
            if ticket.status not in STATUS_ORDER:
                self.warnings.append(f"{ticket.id}: unknown status `{ticket.status}`")
            if ticket.parent and ticket.parent not in self.tickets:
                self.errors.append(f"{ticket.id}: parent `{ticket.parent}` does not exist")
            for dep in ticket.deps:
                if dep not in self.tickets:
                    self.errors.append(f"{ticket.id}: dependency `{dep}` does not exist")
            for link in ticket.links:
                if link not in self.tickets:
                    self.errors.append(f"{ticket.id}: link `{link}` does not exist")

    def config_name(self) -> str:
        try:
            return self.settings.config_path.relative_to(self.root).as_posix()
        except ValueError:
            return str(self.settings.config_path)

    # -- lookups ----------------------------------------------------------

    def entry(self, ticket_id: str) -> dict:
        return self.entries.get(ticket_id, {"modules": (), "summary": ""})

    def primary(self, ticket_id: str) -> str:
        modules = self.entry(ticket_id)["modules"]
        return modules[0] if modules else ""

    def modules_of(self, ticket_id: str) -> tuple[str, ...]:
        return self.entry(ticket_id)["modules"]

    def summary(self, ticket_id: str) -> str:
        return self.entry(ticket_id)["summary"]

    def module_title(self, module_id: str) -> str:
        module = self._modules_by_id.get(module_id)
        return module.title if module else module_id

    def sorted_tickets(self) -> list[Ticket]:
        if self._sorted_cache is None:
            self._sorted_cache = [self.tickets[key] for key in sorted(self.tickets)]
        return self._sorted_cache

    def _group_module_tickets(self) -> tuple[dict[str, list[Ticket]], dict[str, list[Ticket]]]:
        if self._module_tickets_cache is not None and self._module_memberships_cache is not None:
            return self._module_tickets_cache, self._module_memberships_cache

        primary: dict[str, list[Ticket]] = {module.id: [] for module in self.modules}
        memberships: dict[str, list[Ticket]] = {module.id: [] for module in self.modules}
        for ticket in self.sorted_tickets():
            modules = self.modules_of(ticket.id)
            if modules:
                primary.setdefault(modules[0], []).append(ticket)
                for module_id in modules:
                    memberships.setdefault(module_id, []).append(ticket)
        self._module_tickets_cache = primary
        self._module_memberships_cache = memberships
        return primary, memberships

    def module_tickets(self, module_id: str) -> list[Ticket]:
        primary, _ = self._group_module_tickets()
        return primary.get(module_id, [])

    def unresolved(self, ticket: Ticket) -> list[str]:
        if ticket.id not in self._unresolved_cache:
            self._unresolved_cache[ticket.id] = [
                dep
                for dep in ticket.deps
                if dep not in self.tickets or self.tickets[dep].status != "closed"
            ]
        return self._unresolved_cache[ticket.id]

    def is_placeholder_assignee(self, ticket: Ticket) -> bool:
        return ticket.assignee.strip().lower() in self.settings.placeholders

    # -- derived views ----------------------------------------------------

    def tree(self, module_id: str) -> tuple[dict[str, list[Ticket]], list[Ticket]]:
        children: dict[str, list[Ticket]] = defaultdict(list)
        roots: list[Ticket] = []
        for ticket in self.module_tickets(module_id):
            parent = ticket.parent
            if parent and parent in self.tickets and self.primary(parent) == module_id:
                children[parent].append(ticket)
            else:
                roots.append(ticket)

        def child_key(ticket: Ticket) -> tuple[int, int, str]:
            return (STATUS_ORDER.get(ticket.status, 9), ticket.priority, ticket.id)

        for siblings in children.values():
            siblings.sort(key=child_key)
        roots.sort(key=lambda ticket: (0 if ticket.is_map else 1, *child_key(ticket)))

        # A cycle in ``parent`` would leave its members unreachable from any root and
        # silently drop them from the module page. Promote one member of each cycle to
        # a root; ``render_tree`` marks the closing edge.
        reachable: set[str] = set()
        pending = list(roots)
        while pending:
            ticket = pending.pop()
            if ticket.id in reachable:
                continue
            reachable.add(ticket.id)
            pending.extend(children.get(ticket.id, []))
        orphans = [ticket for ticket in self.module_tickets(module_id) if ticket.id not in reachable]
        if orphans:
            roots.extend(sorted(orphans, key=lambda ticket: (0 if ticket.is_map else 1, *child_key(ticket))))
            roots.sort(key=lambda ticket: (0 if ticket.is_map else 1, *child_key(ticket)))
        return children, roots

    def cross_relations(self) -> list[tuple[str, str, str]]:
        relations: list[tuple[str, str, str]] = []
        seen_links: set[tuple[str, str]] = set()
        tickets = self._sorted_cache if self._sorted_cache is not None else self.sorted_tickets()
        for ticket in tickets:
            for dep in ticket.deps:
                if dep in self.tickets and self.primary(dep) != self.primary(ticket.id):
                    relations.append((ticket.id, "depends on", dep))
            for link in ticket.links:
                if link not in self.tickets:
                    continue
                if self.primary(link) == self.primary(ticket.id):
                    continue
                pair = (ticket.id, link) if ticket.id < link else (link, ticket.id)
                if pair in seen_links:
                    continue
                seen_links.add(pair)
                relations.append((pair[0], "linked to", pair[1]))
        return sorted(set(relations))

    # -- rendering --------------------------------------------------------

    def ticket_path(self, ticket_id: str) -> Path:
        return self.settings.tickets_dir / f"{ticket_id}.md"

    def ticket_link(self, ticket_id: str, start: Path) -> str:
        return f"[{ticket_id}]({relative_link(self.ticket_path(ticket_id), start)})"

    def dep_label(self, ticket_id: str, start: Path) -> str:
        if ticket_id not in self.tickets:
            return f"`{ticket_id}` (missing)"
        return f"{self.ticket_link(ticket_id, start)} ({self.tickets[ticket_id].status})"

    def badge_text(self, ticket: Ticket) -> str:
        badges = [ticket.type or "task"]
        if ticket.is_map:
            badges.append("map")
        badges.append(f"P{ticket.priority}")
        badges.append(ticket.status)
        badges.append(ticket.assignee or "unassigned")
        return " ".join(f"`{badge}`" for badge in badges)

    def render_line(
        self, ticket: Ticket, depth: int, module_id: str, start: Path, cycle: bool = False
    ) -> str:
        line = (
            f"{'  ' * depth}- {self.ticket_link(ticket.id, start)} **{ticket.title}**"
            f" — {self.summary(ticket.id)} {self.badge_text(ticket)}"
        )
        extras: list[str] = []
        if ticket.active:
            blocked = self.unresolved(ticket)
            if blocked:
                extras.append("blocked by " + ", ".join(self.dep_label(dep, start) for dep in blocked))
        if ticket.parent:
            if ticket.parent not in self.tickets:
                extras.append(f"parent `{ticket.parent}` (missing)")
            elif self.primary(ticket.parent) != module_id:
                extras.append(
                    f"parent {self.ticket_link(ticket.parent, start)}"
                    f" ({self.module_title(self.primary(ticket.parent))})"
                )
        if cycle:
            extras.append("hierarchy cycle")
        if extras:
            line += " · " + " · ".join(extras)
        return line

    def render_tree(self, module_id: str, start: Path) -> list[str]:
        children, roots = self.tree(module_id)
        if not roots:
            return ["(no tickets in this module)"]

        lines: list[str] = []
        visited: set[str] = set()
        for root in roots:
            stack: list[tuple[Ticket, int, bool]] = [(root, 0, False)]
            active: set[str] = set()
            while stack:
                ticket, depth, exiting = stack.pop()
                if exiting:
                    active.remove(ticket.id)
                    continue
                if ticket.id in active:
                    lines.append(self.render_line(ticket, depth, module_id, start, cycle=True))
                    continue
                if ticket.id in visited:
                    continue
                lines.append(self.render_line(ticket, depth, module_id, start))
                active.add(ticket.id)
                visited.add(ticket.id)
                stack.append((ticket, depth, True))
                for child in reversed(children.get(ticket.id, [])):
                    stack.append((child, depth + 1, False))
        return lines

    def module_stats(self, module_id: str) -> dict[str, int]:
        if module_id not in self._module_stats_cache:
            tickets = self.module_tickets(module_id)
            counts = Counter(ticket.status for ticket in tickets)
            self._module_stats_cache[module_id] = {
                "total": len(tickets),
                "open": counts.get("open", 0),
                "in_progress": counts.get("in_progress", 0),
                "closed": counts.get("closed", 0),
                "active": counts.get("open", 0) + counts.get("in_progress", 0),
                "maps": sum(1 for ticket in tickets if ticket.is_map),
            }
        return self._module_stats_cache[module_id]

    def generated_note(self, start: Path) -> str:
        config_link = relative_link(self.settings.config_path, start)
        return (
            f"{GENERATED_MARK}\n"
            f"> Generated from ticket frontmatter and [`{self.config_name()}`]({config_link})."
            " Do not edit this file by hand."
        )

    def render_module(self, module: Module) -> str:
        stats = self.module_stats(module.id)
        start = self.settings.output_dir / "modules"
        index_link = relative_link(self.settings.output_dir / "INDEX.md", start)
        lines = [
            f"# Module: {module.title}",
            "",
            self.generated_note(start),
            "",
            f"**Scope**: {module.scope or '(not set)'}",
            "",
            f"**Stats**: {stats['total']} tickets · {stats['active']} active"
            f" (open {stats['open']} / in_progress {stats['in_progress']})"
            f" · {stats['closed']} closed · {stats['maps']} maps",
            "",
            "## Ticket hierarchy",
            "",
            *self.render_tree(module.id, start),
        ]

        _, memberships = self._group_module_tickets()
        referenced = [
            ticket
            for ticket in memberships.get(module.id, [])
            if self.primary(ticket.id) != module.id
        ]
        if referenced:
            lines += ["", "## Cross-module membership", ""]
            for ticket in referenced:
                primary = self.primary(ticket.id)
                lines.append(
                    f"- {self.ticket_link(ticket.id, start)} **{ticket.title}**"
                    f" — {self.summary(ticket.id)}"
                    f" (primary module: [{self.module_title(primary)}]({primary}.md))"
                )
        lines.append("")
        return "\n".join(lines)

    def render_index(self) -> str:
        start = self.settings.output_dir
        tickets = self.sorted_tickets()
        status_counts = Counter(ticket.status for ticket in tickets)
        type_counts = Counter(ticket.type or "task" for ticket in tickets)
        active = [ticket for ticket in tickets if ticket.active]
        frontier = [ticket for ticket in active if not self.unresolved(ticket)]
        blocked = [ticket for ticket in active if self.unresolved(ticket)]
        ownerless = [ticket for ticket in active if self.is_placeholder_assignee(ticket)]
        relations = self.cross_relations()
        multi_module = [ticket for ticket in tickets if len(self.modules_of(ticket.id)) > 1]

        lines = [
            f"# {self.settings.title}",
            "",
            self.generated_note(start),
            "",
            "## How to read this file",
            "",
            "- Locate a ticket through the module table, open that module, then read only the ticket you need.",
            "- `open` means ready to start, `in_progress` means being worked on, `closed` means accepted.",
            "  **Active** means `open` or `in_progress`.",
            "- `map` marks a decision map. Hierarchy comes only from `parent`; `links` express associations.",
            "- A multi-module ticket is expanded only in its primary module.",
            "",
            "## Overview",
            "",
            f"- Tickets **{len(tickets)}**: open {status_counts.get('open', 0)}"
            f" · in_progress {status_counts.get('in_progress', 0)}"
            f" · closed {status_counts.get('closed', 0)}",
            "- Types: "
            + " · ".join(
                f"{name} {count}"
                for name, count in sorted(type_counts.items(), key=lambda item: (-item[1], item[0]))
            ),
            f"- Maps {sum(1 for ticket in tickets if ticket.is_map)}"
            f" · Active {len(active)} · Cross-module relations {len(relations)}",
            "",
            "## Owners (active tickets)",
            "",
            "| Owner | open | in_progress | active |",
            "| --- | ---: | ---: | ---: |",
        ]

        by_assignee: dict[str, list[Ticket]] = defaultdict(list)
        for ticket in active:
            by_assignee[ticket.assignee.strip() or "Unassigned"].append(ticket)
        for assignee, owned in sorted(by_assignee.items(), key=lambda item: (-len(item[1]), item[0])):
            open_count = sum(1 for ticket in owned if ticket.status == "open")
            progress_count = sum(1 for ticket in owned if ticket.status == "in_progress")
            shown = (
                f"{assignee} (placeholder)"
                if assignee.strip().lower() in self.settings.placeholders
                else assignee
            )
            lines.append(f"| {cell(shown)} | {open_count} | {progress_count} | {len(owned)} |")
        if not by_assignee:
            lines.append("| (no active tickets) | 0 | 0 | 0 |")

        lines += [
            "",
            "## Modules",
            "",
            "| Module | Scope | Tickets | Active | Maps |",
            "| --- | --- | ---: | ---: | ---: |",
        ]
        for module in self.modules:
            stats = self.module_stats(module.id)
            module_link = relative_link(self.settings.output_dir / "modules" / f"{module.id}.md", start)
            lines.append(
                f"| [{module.title}]({module_link}) | {cell(module.scope) or '—'}"
                f" | {stats['total']} | {stats['active']} | {stats['maps']} |"
            )
        if not self.modules:
            lines.append("| (no modules configured) | — | 0 | 0 | 0 |")

        lines += [
            "",
            "## Frontier",
            "",
            "Active tickets whose dependencies are all closed.",
            "",
            "| Ticket | Module | Owner |",
            "| --- | --- | --- |",
        ]
        for ticket in sorted(frontier, key=lambda item: (item.priority, item.id)):
            lines.append(
                f"| {self.ticket_link(ticket.id, start)} {cell(ticket.title)}"
                f" | {self.module_title(self.primary(ticket.id))}"
                f" | {cell(ticket.assignee) or 'unassigned'} |"
            )
        if not frontier:
            lines.append("| (none) | — | — |")

        lines += [
            "",
            "## Blocked",
            "",
            "| Ticket | Module | Blocked by |",
            "| --- | --- | --- |",
        ]
        for ticket in sorted(blocked, key=lambda item: (item.priority, item.id)):
            deps = ", ".join(self.dep_label(dep, start) for dep in self.unresolved(ticket))
            lines.append(
                f"| {self.ticket_link(ticket.id, start)} {cell(ticket.title)}"
                f" | {self.module_title(self.primary(ticket.id))}"
                f" | {deps} |"
            )
        if not blocked:
            lines.append("| (none) | — | — |")

        lines += [
            "",
            "## Missing owners",
            "",
            "Active tickets whose `assignee` is empty or a placeholder.",
            "",
            "| Ticket | Status | Assignee |",
            "| --- | --- | --- |",
        ]
        for ticket in sorted(ownerless, key=lambda item: (item.priority, item.id)):
            lines.append(
                f"| {self.ticket_link(ticket.id, start)} {cell(ticket.title)}"
                f" | {ticket.status} | `{cell(ticket.assignee) or 'empty'}` |"
            )
        if not ownerless:
            lines.append("| (none) | — | — |")

        lines += [
            "",
            "## Cross-module relations",
            "",
            "### Multi-module membership",
            "",
            "| Ticket | Primary module | Also belongs to |",
            "| --- | --- | --- |",
        ]
        for ticket in multi_module:
            modules = self.modules_of(ticket.id)
            others = ", ".join(self.module_title(module_id) for module_id in modules[1:])
            lines.append(
                f"| {self.ticket_link(ticket.id, start)} {cell(ticket.title)}"
                f" | {self.module_title(modules[0])} | {others} |"
            )
        if not multi_module:
            lines.append("| (none) | — | — |")

        lines += [
            "",
            "### Dependencies and links",
            "",
            "Only cross-module edges are listed; symmetric links appear once.",
            "",
            "| Ticket | Relation | Other ticket | Modules involved |",
            "| --- | --- | --- | --- |",
        ]
        for source, kind, target in relations:
            modules = sorted(
                {
                    self.module_title(self.primary(source)),
                    self.module_title(self.primary(target)),
                }
            )
            lines.append(
                f"| {self.ticket_link(source, start)} | {kind}"
                f" | {self.ticket_link(target, start)} | {', '.join(modules)} |"
            )
        if not relations:
            lines.append("| (none) | — | — |")

        lines += [
            "",
            "## Maintenance",
            "",
            "- Facts live in ticket frontmatter; change them with your ticket CLI, not in generated files.",
            f"- Module ownership and summaries live in `{self.config_name()}`.",
            "- Review changes with `diff`; write them with `render`; verify with `check`.",
            "- `check` exits non-zero on missing entries, unknown modules, broken references, or stale output.",
            "",
        ]
        return "\n".join(lines)

    def expected_files(self) -> dict[Path, str]:
        files = {self.settings.output_dir / "INDEX.md": self.render_index()}
        for module in self.modules:
            files[self.settings.output_dir / "modules" / f"{module.id}.md"] = self.render_module(module)
        return files


