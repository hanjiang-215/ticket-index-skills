def print_problems(problems: list[str], warnings: list[str]) -> None:
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    if problems:
        print(f"{len(problems)} problem(s):", file=sys.stderr)
        for problem in problems:
            print(f"- {problem}", file=sys.stderr)


def cmd_check(index: Index) -> int:
    problems = list(index.errors)
    expected = index.expected_files()
    for path, content in expected.items():
        relative = path.relative_to(index.root) if path.is_relative_to(index.root) else path
        if not path.is_file():
            problems.append(f"missing generated file {relative} (run render)")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"stale generated file {relative} (run render)")

    managed = {path.resolve() for path in expected}
    modules_dir = index.settings.output_dir / "modules"
    if modules_dir.is_dir():
        for path in sorted(modules_dir.glob("*.md")):
            if path.resolve() in managed:
                continue
            if GENERATED_MARK in path.read_text(encoding="utf-8")[:600]:
                try:
                    shown = path.relative_to(index.root).as_posix()
                except ValueError:
                    shown = str(path)
                problems.append(f"obsolete generated file {shown} (run render)")

    print_problems(problems, index.warnings)
    if problems:
        return 1
    print(
        f"OK: {len(index.tickets)} tickets, {len(index.modules)} modules, generated files are current."
    )
    return 0


def cmd_diff(index: Index) -> int:
    changed = 0
    for path, expected in index.expected_files().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current == expected:
            continue
        changed += 1
        try:
            relative = path.relative_to(index.root).as_posix()
        except ValueError:
            relative = str(path)
        print(f"### {relative}")
        print(
            "\n".join(
                difflib.unified_diff(
                    current.splitlines(),
                    expected.splitlines(),
                    fromfile=f"a/{relative}",
                    tofile=f"b/{relative}",
                    lineterm="",
                )
            )
        )
        print()

    print_problems([], index.warnings)
    if changed:
        print(f"{changed} generated file(s) would change. Review the hunks, then run render.")
    else:
        print("Generated files are already current; nothing to review.")
    return 0


def cmd_render(index: Index) -> int:
    if index.errors:
        print_problems(index.errors, index.warnings)
        print("Config has errors; nothing was written.", file=sys.stderr)
        return 1

    with render_lock(index.root):
        fresh_index = Index(load_config(index.settings.config_path))
        if fresh_index.errors:
            print_problems(fresh_index.errors, fresh_index.warnings)
            print("Config has errors; nothing was written.", file=sys.stderr)
            return 1
        return _render_locked(fresh_index)


def _render_locked(index: Index) -> int:
    written = 0
    unchanged = 0
    expected = index.expected_files()
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            unchanged += 1
            continue
        path.write_text(content, encoding="utf-8", newline="\n")
        written += 1

    removed = 0
    modules_dir = index.settings.output_dir / "modules"
    managed = {path.resolve() for path in expected}
    if modules_dir.is_dir():
        for path in sorted(modules_dir.glob("*.md")):
            if path.resolve() in managed:
                continue
            if GENERATED_MARK in path.read_text(encoding="utf-8")[:600]:
                path.unlink()
                removed += 1

    print_problems([], index.warnings)
    print(
        f"Generated {len(expected)} file(s): written {written}, unchanged {unchanged}, removed {removed}."
    )
    return 0


def cmd_facts(index: Index) -> int:
    header = ["id", "status", "type", "assignee", "primary_module", "parent", "summary", "title"]
    print("\t".join(header))
    for ticket in index.sorted_tickets():
        entry = index.entries.get(ticket.id)
        summary = entry["summary"] if entry else "[missing config entry]"
        module = index.primary(ticket.id) or "[unassigned module]"
        values = [
            ticket.id,
            ticket.status,
            ticket.type,
            ticket.assignee or "[unassigned]",
            module,
            ticket.parent or "-",
            summary,
            ticket.title,
        ]
        print("\t".join(values))
    return 0


# Suffix alphabet is intentionally small (letters + digits) to match the kit's
# conventional `-[0-9a-z]{4}` suffix; ``new-id`` re-checks against the configured
# id_pattern, so a tighter pattern still yields valid ids.
NEW_ID_SUFFIX_ALPHABET = "abcdefghijklmnopqrstuvwxyz0123456789"
NEW_ID_SUFFIX_LITERAL = "-[0-9a-z]{4}"


def cmd_new_id(index: Index, prefix: str | None) -> int:
    """Print one ticket id that is not yet used in the configured ticket store.

    This is the coordination guard for parallel ticket creation: two sessions that
    both call ``new-id`` on the same branch cannot silently pick the same filename.
    It reads existing ids from the tickets directory (never the network), so the
    guarantee is local; cross-branch collisions surface as a normal merge conflict
    on the ticket file and are resolved by renaming one side.
    """
    tickets_dir = index.settings.tickets_dir
    existing: set[str] = set()
    if tickets_dir.is_dir():
        for path in tickets_dir.glob("*.md"):
            if path.stem.lower() == "readme":
                continue
            if index.id_pattern.fullmatch(path.stem):
                existing.add(path.stem)

    if prefix is None:
        pattern_text = index.settings.id_pattern
        if pattern_text.endswith(NEW_ID_SUFFIX_LITERAL):
            head = pattern_text[: -len(NEW_ID_SUFFIX_LITERAL)]
            if head and not re.search(r"[\[\]\\?*+^$.{}()|]", head):
                prefix = head
    if prefix is None:
        print(
            "Cannot infer a literal prefix from id_pattern; pass --prefix, "
            "e.g. --prefix app.",
            file=sys.stderr,
        )
        return 2

    mismatch = 0
    for _ in range(200):
        suffix = "".join(random.choice(NEW_ID_SUFFIX_ALPHABET) for _ in range(4))
        candidate = f"{prefix}-{suffix}"
        if candidate in existing:
            continue
        if not index.id_pattern.fullmatch(candidate):
            mismatch += 1
            if mismatch >= 50:
                print(
                    f"The prefix `{prefix}` does not produce ids matching "
                    f"id_pattern `{index.settings.id_pattern}`.",
                    file=sys.stderr,
                )
                return 1
            continue
        print(candidate)
        return 0
    print(
        "Could not mint a fresh id after 200 attempts; every candidate collided "
        "with an existing id.",
        file=sys.stderr,
    )
    return 1


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", help="Path to ticket-index.toml (default: search upward)")
    parser.add_argument(
        "--prefix",
        help="Ticket id prefix for `new-id` (default: inferred from id_pattern)",
    )
    parser.add_argument(
        "command",
        nargs="?",
        choices=["facts", "check", "diff", "render", "new-id"],
        default="check",
    )
    args = parser.parse_args()

    config_path = find_config(args.config)
    config = load_config(config_path)
    index = Index(config)

    if args.command == "facts":
        return cmd_facts(index)
    if args.command == "diff":
        return cmd_diff(index)
    if args.command == "render":
        return cmd_render(index)
    if args.command == "new-id":
        return cmd_new_id(index, args.prefix)
    return cmd_check(index)


if __name__ == "__main__":
    raise SystemExit(main())
